// Regenerates the SDK's known-asset list from the Based Loans frontend registry.
// Usage: node scripts/sync-assets.mjs <path/to/basedloans/lib/assets.ts> <out.ts>
//
// The list is metadata only (symbol, name, decimals). Every SDK call verifies status, price,
// limits and risk on-chain, so a stale list can only hide a new asset, never misprice one.
import { readFileSync, writeFileSync } from "fs"

const [src, out] = process.argv.slice(2)
if (!src || !out) {
  console.error("usage: sync-assets.mjs <assets.ts> <out.ts>")
  process.exit(1)
}
const text = readFileSync(src, "utf8")

function section(name, from = 0) {
  const start = text.indexOf(name, from)
  if (start < 0) return ""
  const open = text.indexOf("[", start)
  let depth = 0
  for (let i = open; i < text.length; i++) {
    if (text[i] === "[") depth++
    else if (text[i] === "]" && --depth === 0) return text.slice(open, i + 1)
  }
  return ""
}

function parse(block) {
  const items = []
  const re = /\{[^{}]*?address:\s*"(0x[0-9a-fA-F]{40})"[^{}]*?symbol:\s*"([^"]+)"[^{}]*?name:\s*"([^"]+)"[^{}]*?decimals:\s*(\d+)[^{}]*?\}/g
  let m
  while ((m = re.exec(block))) items.push({ address: m[1], symbol: m[2], name: m[3], decimals: Number(m[4]) })
  return items
}

const activeStart = text.indexOf("ASSETS_BY_CHAIN")
const retiredStart = text.indexOf("RETIRED_ASSETS_BY_CHAIN")
const mainnet = section("8453:", activeStart)
const retired = retiredStart >= 0 ? section("8453:", retiredStart) : ""
const active = parse(mainnet)
const old = parse(retired)
if (active.length < 10) {
  console.error(`only parsed ${active.length} assets; the registry format probably changed`)
  process.exit(1)
}

const body = `// Generated by scripts/sync-assets.mjs from the Based Loans frontend asset registry. Do not edit.
// Metadata only. Status, prices, limits and risk are always read on-chain.
import type { KnownAsset } from "./types.js"

export const KNOWN_ASSETS: readonly KnownAsset[] = ${JSON.stringify(active, null, 2)}

export const RETIRED_ASSETS: readonly KnownAsset[] = ${JSON.stringify(old, null, 2)}
`
writeFileSync(out, body)
console.log(`wrote ${active.length} known + ${old.length} retired assets to ${out}`)
